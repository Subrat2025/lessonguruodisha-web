// ============================================================================
//  Dedicated Gemini prompts — Professional Assessment Builder
//  ---------------------------------------------------------------------------
//  Each question type has its OWN prompt template — no generic prompt.  Every
//  prompt is grounded in the read-only lesson context and requires strict
//  Odia SCERT/OSEPA examination style output.
//
//  Guarantees applied to every prompt:
//    • Use ONLY the provided lesson content as the source of facts.
//    • Odia (ଓଡ଼ିଆ) output by default (never Latin transliterations).
//    • No fictional characters or made-up stories unless the type explicitly
//      requires it (Case Study, Activity Based, Project Based).
//    • Direct, natural, human-written phrasing — no marketing/AI voice.
//    • JSON output only, matching the schema shown to the model.
// ============================================================================

import { buildScertPersonaBlock } from './persona.js'

// commonRules(language) — returns the strict writing style block used by every
// prompt. Supports language: 'odia' (default) or 'english'. For English-subject
// assessments (across all classes), we switch to full English output.
//
// The block now prepends the full SCERT / OSEPA teacher persona so every
// question-type prompt is generated by a "30-year veteran teacher" persona
// with lesson-grounded, human-written mandate, class-level rules, picture
// verification rules, and a self-review checklist.
function commonRules(language = 'odia', className = '') {
  const personaBlock = buildScertPersonaBlock({
    language,
    className,
    includeIdentity: true,
    includeQuality: true,
    includeLessonOnly: true,
    includeStyle: true,
    includeDifficulty: true,
    includeClassLevel: true,
    includePicture: true,
    includeSelfReview: true,
  })
  const styleTail = (language === 'english') ? `
STRICT WRITING STYLE (VIOLATION = INVALID OUTPUT):
- Language: English — full English words and sentences ONLY (no Odia script, no transliteration).
- Digits: Arabic numerals (1, 2, 3 …) with standard English punctuation.
- Voice: exam-style, formal, addressed to the student.
- Concise. No preamble, no "let us learn today", no motivational lines.
- Vocabulary MUST come from the lesson content shown above.
- Do NOT introduce facts, examples, characters, or places that are not in
  the lesson (unless the question type requires a case study, activity or
  project — in that case invent MINIMAL supporting details rooted in Odisha).
- Do NOT reveal answers in the question stem.
- Grammar, spelling, and punctuation must be textbook-quality British-Indian English.
`.trim() : `
STRICT WRITING STYLE (VIOLATION = INVALID OUTPUT):
- Language: Odia (ଓଡ଼ିଆ) — Odia script, Odia digits (୧ ୨ ୩ …), Odia punctuation।
- Voice: exam-style, formal, addressed to the student.
- Concise. No preamble, no "let us learn today", no motivational lines.
- Vocabulary MUST come from the lesson content shown above.
- Do NOT introduce facts, examples, characters, or places that are not in
  the lesson (unless the question type requires a case study, activity or
  project — in that case invent MINIMAL supporting details rooted in Odisha).
- Do NOT reveal answers in the question stem.
- All numeric options / blanks / marks references must be in Odia numerals.
`.trim()
  return `${personaBlock}\n\n${styleTail}`
}
