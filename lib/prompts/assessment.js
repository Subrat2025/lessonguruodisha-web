// The Blueprint is generated deterministically from the sections + LOs/Bloom
// levels chosen in the registry — no Gemini call needed for it.  Exported here
// so builders and HTML render can share the shape.
export function buildBlueprintFromSections({ sections, chapters, loCodes }) {
  const chapterNames = (chapters || []).map(c => c.name).filter(Boolean).join(', ')
  const rows = []
  let qNo = 1
  for (const s of sections) {
    for (let i = 0; i < s.count; i++) {
      const lo = (loCodes && loCodes[qNo % Math.max(1, loCodes.length)]) || null
      rows.push({
        qNo,
        section: s.sectionLetterOdia,
        type: s.label,
        typeOdia: s.labelOdia,
        chapter: chapterNames,
        loCode: lo?.code || '',
        loDescription: (lo?.description || '').slice(0, 90),
        competency: lo?.competency || '—',
        bloom: (s.bloom || 'Understand'),
        marks: s.marksPerQ,
      })
      qNo += 1
    }
  }
  return rows
}
