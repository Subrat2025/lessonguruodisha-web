/** VSA / SA / LA — free-form answers with model answer.  Same schema, different length target. */
const _promptOpenAnswer = (kind) => ({ count, contextBlock, difficultyMix, marksPerQ, language = 'odia', className = '' }) => {
  const sentences =
    kind === 'vsa' ? '1 sentence answer' :
    kind === 'sa'  ? '2–3 sentence answer' :
    /* la */         '5–8 sentence answer, well-structured, showing understanding'
  const label =
    kind === 'vsa' ? 'Very Short Answer' :
    kind === 'sa'  ? 'Short Answer' :
                     'Long Answer'
  return {
    prompt: `${contextBlock}

TASK: Write ${count} ${label} questions (worth ${marksPerQ} marks each).

REQUIREMENTS:
- Model answer length: ${sentences}.
- Every question must clearly test understanding of the lesson.
- Model answer must reuse the lesson's exact terminology and named examples wherever possible.
- Difficulty mix: ${difficultyMix.easy} Easy, ${difficultyMix.medium} Medium, ${difficultyMix.hard} Hard.

${commonRules(language, className)}

${OUTPUT_JSON_ONLY}`,
    schema: {
      type: 'object',
      properties: {
        questions: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              q: { type: 'string' },
              answer: { type: 'string', description: `Model ${label.toLowerCase()} in Odia` },
              difficulty: { type: 'string', enum: ['E', 'M', 'H'] },
              lo: { type: 'string' },
            },
            required: ['q', 'answer'],
          },
        },
      },
      required: ['questions'],
    },
  }
}
export const promptVSA = _promptOpenAnswer('vsa')
