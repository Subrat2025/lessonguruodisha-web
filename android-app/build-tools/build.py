"""Builds the signed APK and AAB without Gradle / the Android SDK manager.

Toolchain (see README):
  android.jar  - compile classpath (API 35)
  bundletool   - provides D8 (dexer), apksig (APK signing) and build-bundle
  JDK          - javac, keytool, jarsigner

Usage: python3 build.py [--tools /home/user/tools]
"""
import argparse
import os
import shutil
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BUILD = os.path.join(ROOT, 'build')
DIST = os.path.join(ROOT, 'dist')

VERSION_CODE = 9
VERSION_NAME = '1.7.0'
MIN_SDK = 24
APP_ID = 'com.lessonguruodisha.app'          # Play Store version: nothing sold in the app
DIRECT_APP_ID = APP_ID + '.direct'           # direct APK (website / WhatsApp): Razorpay + UPI inside
KEY_ALIAS = 'lessonguru'

NO_COMPRESS = ('.png', '.jpg', '.webp', '.woff2', '.arsc')


def run(cmd, **kw):
    print('$', ' '.join(cmd) if isinstance(cmd, list) else cmd)
    subprocess.run(cmd, check=True, **kw)


def keystore():
    ks = os.path.join(ROOT, 'keystore', 'lessonguru-upload.p12')
    props = os.path.join(ROOT, 'keystore', 'keystore.properties')
    if not os.path.exists(ks):
        os.makedirs(os.path.dirname(ks), exist_ok=True)
        import secrets
        pw = secrets.token_urlsafe(18)
        run(['keytool', '-genkeypair', '-storetype', 'PKCS12', '-keystore', ks, '-alias', KEY_ALIAS,
             '-keyalg', 'RSA', '-keysize', '4096', '-validity', '10000', '-storepass', pw, '-keypass', pw,
             '-dname', 'CN=Lesson Guru Odisha, OU=Mobile, O=Teacher Utility Tool Kit, L=Bhubaneswar, ST=Odisha, C=IN'])
        with open(props, 'w') as f:
            f.write(f'storeFile=lessonguru-upload.p12\nkeyAlias={KEY_ALIAS}\nstorePassword={pw}\nkeyPassword={pw}\n')
    pw = dict(l.strip().split('=', 1) for l in open(props) if '=' in l)['storePassword']
    return ks, pw


def write_aligned_zip(path, entries):
    """entries: list of (arcname, bytes). STORED entries are 4-byte aligned (zipalign-equivalent)."""
    with zipfile.ZipFile(path, 'w') as z:
        for name, data in entries:
            zi = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            zi.external_attr = 0o644 << 16
            stored = name.endswith(NO_COMPRESS)
            zi.compress_type = zipfile.ZIP_STORED if stored else zipfile.ZIP_DEFLATED
            if stored:
                offset = z.fp.tell() + 30 + len(name.encode())
                pad = (-(offset + 6)) % 4  # 0xD935 alignment extra: id, size, alignment + padding
                zi.extra = (0xD935).to_bytes(2, 'little') + (2 + pad).to_bytes(2, 'little') + \
                    (4).to_bytes(2, 'little') + b'\0' * pad
            z.writestr(zi, data, compresslevel=9 if not stored else None)


def collect(dir_, prefix):
    out = []
    for base, _, files in os.walk(dir_):
        for fn in sorted(files):
            full = os.path.join(base, fn)
            rel = os.path.relpath(full, dir_).replace(os.sep, '/')
            out.append((prefix + rel, open(full, 'rb').read()))
    return sorted(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tools', default='/home/user/tools')
    ap.add_argument('--flavor', choices=['play', 'direct'], default='play')
    args = ap.parse_args()
    direct = args.flavor == 'direct'
    os.environ['LG_APP_ID'] = DIRECT_APP_ID if direct else APP_ID
    tag = 'Direct-' if direct else ''
    android_jar = os.path.join(args.tools, 'android-35.jar')
    bundletool = os.path.join(args.tools, 'bundletool.jar')

    shutil.rmtree(BUILD, ignore_errors=True)
    os.makedirs(BUILD)
    os.makedirs(DIST, exist_ok=True)

    # 1) resources
    run([sys.executable, '-I', os.path.join(HERE, 'res_build.py'), ROOT, os.path.join(BUILD, 'res'),
         str(VERSION_CODE), VERSION_NAME])
    tools_cls = os.path.join(BUILD, 'tools')
    run(['javac', '-nowarn', '-cp', bundletool, '-d', tools_cls,
         os.path.join(HERE, 'ProtoGen.java'), os.path.join(HERE, 'Signer.java')])
    run(['java', '-cp', f'{bundletool}:{tools_cls}', 'ProtoGen',
         os.path.join(BUILD, 'res', 'spec.json'), os.path.join(BUILD, 'res', 'aab')])

    # 2) java -> class -> dex
    gen = os.path.join(BUILD, 'gen', 'com', 'lessonguruodisha', 'app')
    os.makedirs(gen)
    with open(os.path.join(gen, 'BuildInfo.java'), 'w') as f:
        f.write('package com.lessonguruodisha.app;\n\n/** Generated by build.py. */\n'
                'public final class BuildInfo {\n'
                f'    public static final String VERSION_NAME = "{VERSION_NAME}";\n'
                f'    public static final int VERSION_CODE = {VERSION_CODE};\n'
                f'    /** Direct version (outside Play): purchases with Razorpay/UPI inside the app. */\n'
                f'    public static final boolean DIRECT = {"true" if direct else "false"};\n'
                '    private BuildInfo() {\n    }\n}\n')
    srcs = []
    for base in (os.path.join(ROOT, 'src', 'main', 'java'), os.path.join(BUILD, 'gen')):
        for d, _, fs in os.walk(base):
            srcs += [os.path.join(d, x) for x in fs if x.endswith('.java')]
    stubs = os.path.join(BUILD, 'stubs')
    run(['javac', '-Xlint:-options', '-source', '8', '-target', '8', '-bootclasspath', android_jar, '-d', stubs,
         os.path.join(HERE, 'stubs', 'java', 'lang', 'invoke', 'LambdaMetafactory.java')])
    classes = os.path.join(BUILD, 'classes')
    run(['javac', '-Xlint:-options', '-source', '8', '-target', '8', '-encoding', 'UTF-8',
         '-bootclasspath', f'{android_jar}:{stubs}', '-d', classes] + srcs)
    class_files = [os.path.join(d, x) for d, _, fs in os.walk(classes) for x in fs if x.endswith('.class')]
    dex_dir = os.path.join(BUILD, 'dex')
    os.makedirs(dex_dir)
    run(['java', '-cp', bundletool, 'com.android.tools.r8.D8', '--release', '--min-api', str(MIN_SDK),
         '--lib', android_jar, '--output', dex_dir] + class_files)
    dex = open(os.path.join(dex_dir, 'classes.dex'), 'rb').read()

    assets = collect(os.path.join(ROOT, 'src', 'main', 'assets'), 'assets/')
    apk_res = collect(os.path.join(BUILD, 'res', 'apk'), '')

    # 3) APK
    unsigned = os.path.join(BUILD, 'app-unsigned.apk')
    order = sorted(apk_res, key=lambda e: (e[0] != 'AndroidManifest.xml', e[0] != 'resources.arsc', e[0]))
    write_aligned_zip(unsigned, order + [('classes.dex', dex)] + assets)
    ks, pw = keystore()
    apk = os.path.join(DIST, f'LessonGuruOdisha-{tag}v{VERSION_NAME}.apk')
    run(['java', '-cp', f'{bundletool}:{tools_cls}', 'Signer', unsigned, apk, ks, KEY_ALIAS, pw, str(MIN_SDK)])

    # 4) AAB (base module in proto format)
    module = os.path.join(BUILD, 'base.zip')
    aab_res = collect(os.path.join(BUILD, 'res', 'aab'), '')
    pngs = [(n, d) for n, d in apk_res if n.endswith('.png')]
    write_aligned_zip(module, sorted(aab_res + pngs) + [('dex/classes.dex', dex)] + assets)
    aab_unsigned = os.path.join(BUILD, 'app-unsigned.aab')
    run(['java', '-jar', bundletool, 'build-bundle', f'--modules={module}', f'--output={aab_unsigned}', '--overwrite'])
    aab = os.path.join(DIST, f'LessonGuruOdisha-{tag}v{VERSION_NAME}.aab')
    shutil.copyfile(aab_unsigned, aab)
    run(['jarsigner', '-sigalg', 'SHA256withRSA', '-digestalg', 'SHA-256', '-keystore', ks,
         '-storepass', pw, aab, KEY_ALIAS])
    run(['java', '-jar', bundletool, 'validate', f'--bundle={aab}'], stdout=subprocess.DEVNULL)
    print('\nBUILD OK')
    for p in (apk, aab):
        print(f'  {p}  ({os.path.getsize(p) / 1024:.0f} KB)')


if __name__ == '__main__':
    main()
